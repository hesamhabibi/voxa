// Domain models for Voxa. Persistence layer is not decided yet (see docs/VOXA_CONTEXT.md).

export type ISODate = string // "2026-10-21"

export type QuestionLevel = "unrated" | "beginner" | "intermediate" | "advanced"

export interface SampleAnswer {
  id: string
  /** Target sentence count: sample 1 ≈ 5, sample 2 ≈ 7, sample 3 ≈ 10 (always 5–10). */
  sentences: string[]
  /** Future: band-specific samples (7, 8) reviewed by a teacher. */
  band?: 7 | 8
  teacherVerified?: boolean
}

export interface SpeakingQuestion {
  id: string
  /** e.g. "ielts-part-1" */
  category: string
  level: QuestionLevel
  text: string
  samples: SampleAnswer[]
}

export interface SelfTalkSession {
  id: string
  date: ISODate
  startedAt: string
  endedAt?: string
  durationMinutes: number
  questionIds: string[]
  status: "in-progress" | "finished"
}

export type WordStatus = "new" | "practiced" | "learning" | "known"

export interface DictionaryWord {
  id: string
  english: string
  persian: string
  addedAt: string
  /** Session in which the learner added the word. */
  sessionId?: string
  sourceQuestionId?: string
  status: WordStatus
  /** Examples generated by AI (3 per batch, refreshable). */
  aiExamples: string[]
  /** Exactly 5 sentences written by the learner in Self-dictionary. */
  userSentences: string[]
}

export type ReviewResult = "right" | "wrong"

export interface ReviewAttempt {
  id: string
  wordId: string
  date: ISODate
  persianAnswer: string
  sentenceAnswer: string
  result: ReviewResult
  judgedBy: "ai" | "user"
}

/** Spaced-repetition state per word (Ebbinghaus intervals are TBD). */
export interface ReviewSchedule {
  wordId: string
  lastReviewedAt?: ISODate
  nextReviewAt: ISODate
  correctStreak: number
  wrongCount: number
}

export interface UserSettings {
  selfTalkMinutes: number
  reviewWordsPerNight: number
}
